"""Storage interface (v3 STO-1): what a storage backend must provide.

Two stores:
- DocumentStore: chunks, their vectors and metadata (the vector index).
- StateStore: sessions, jobs, watches, reports, feedback, prefs, query log,
  ingest log, paper index and metadata cache.

The local backend is the existing code: the `vector_store` module (ChromaDB) and
the `persistence` module (SQLite) satisfy these protocols as they are, so callers
keep importing them and local mode changes nothing. A server backend (STO-2,
Postgres + pgvector) implements the same protocols, and those two modules become
facades that dispatch to whichever backend STORAGE_BACKEND selects.

The seam is enforced, not just declared: production code outside vector_store.py
must not import chromadb or call collection methods directly, and outside
persistence.py must not open SQLite (.unlazy/v3-phase1/check_storage_boundary.py).
tests/test_storage_contract.py runs the behavioural contract against each backend.

`collection` arguments are opaque handles from get_or_create_collection(); only the
backend that issued one may interpret it.
"""

from typing import Any, Dict, List, Optional, Protocol, runtime_checkable


@runtime_checkable
class DocumentStore(Protocol):
    CHUNKER_VERSION: int

    def get_or_create_collection(self, collection_name: str = None, reset: bool = False) -> Any: ...
    def add_documents(self, texts: List[str], embeddings, metadatas: List[Dict], ids: List[str],
                      collection: Any = None) -> None: ...
    def search(self, query_embedding, top_k: int = None, filter_dict: Optional[Dict] = None,
               collection: Any = None) -> Dict[str, List]: ...
    def get_chunks(self, collection: Any = None, *, ids: List[str] = None, where: Dict = None,
                   include=("documents", "metadatas"), limit: int = None,
                   timeout: Optional[float] = 5.0) -> Dict[str, Any]: ...
    def count(self, collection: Any = None, *, timeout: Optional[float] = 5.0) -> int: ...
    def get_paper_chunk_counts(self, collection: Any = None) -> Dict[str, int]: ...
    def update_paper_metadata(self, paper_id: str, updates: dict, collection: Any = None) -> int: ...
    def delete_stale_chunks(self, paper_id: str, keep_ids: List[str], collection: Any = None) -> int: ...
    def delete_by_paper_id(self, paper_id: str, collection: Any = None) -> int: ...
    def find_similar_paper(self, title: str, year: str = None, threshold: float = 0.9,
                           collection: Any = None) -> Optional[str]: ...
    def index_fingerprint(self, collection: Any = None) -> Optional[Dict[str, Any]]: ...
    def check_index_compatibility(self, collection: Any = None) -> Optional[str]: ...
    def embed_backend(self) -> str: ...
    def chroma_circuit_open(self) -> bool: ...   # "the vector backend is unavailable"; name kept for callers


@runtime_checkable
class StateStore(Protocol):
    # transactions and backup
    def batch_writes(self): ...
    def snapshot_to(self, dest_path) -> dict: ...
    def restore_from(self, src_path) -> dict: ...
    def checkpoint(self) -> None: ...
    # sessions and jobs
    def load_sessions(self, max_age_hours: int = None) -> dict: ...
    def save_session(self, session_id: str, session: dict) -> None: ...
    def delete_session(self, session_id: str) -> None: ...
    def load_jobs(self, max_age_hours: int = 24) -> dict: ...
    def save_job(self, job_id: str, job: dict, lease_until: str = None) -> None: ...
    def delete_job(self, job_id: str) -> None: ...
    def reap_stale_jobs(self, now_iso: str) -> list: ...
    # feedback, query log, prefs
    def save_feedback(self, *a, **k) -> None: ...
    def log_query(self, *a, **k) -> None: ...
    def get_feedback_with_context(self, *a, **k) -> Any: ...
    def feedback_stats(self, owner: str | None = None) -> dict: ...
    def get_prefs(self, user_id: str) -> dict: ...
    def save_prefs(self, user_id: str, prefs: dict, updated_at: str) -> None: ...
    # watches and reports
    def save_watch(self, watch: dict) -> None: ...
    def get_watch(self, watch_id: str) -> dict | None: ...
    def list_watches(self, user_id: str | None = None, owner: str | None = None) -> list: ...
    def owns_watch(self, watch: dict | None, owner: str | None) -> bool: ...
    def due_watches(self, now_iso: str) -> list: ...
    def claim_watch(self, watch_id: str, expected_next_run: str, lease_until: str) -> bool: ...
    def delete_watch(self, watch_id: str) -> None: ...
    def save_report(self, *a, **k) -> None: ...
    def get_report(self, report_id: str, owner: str | None = None) -> dict | None: ...
    def list_reports(self, watch_id: str | None = None, owner: str | None = None) -> list: ...
    # ingest log (the system of record for the derived indexes) and paper index
    def record_ingest(self, event_id: str, paper_id: str, content_hash: str, title: str,
                      source_path: str, chunks: list, metadatas: list, ids: list,
                      embed_model: str, chunker_version: int, created_at: str,
                      embed_backend: str = None) -> None: ...
    def get_ingest_events(self, paper_id: str = None) -> list: ...
    def delete_ingest_events(self, paper_id: str) -> int: ...
    def clear_ingest_log(self) -> int: ...
    def ingest_event_count(self) -> int: ...
    def list_papers(self) -> list: ...
    def get_metadata_cache(self, title_key: str): ...
    def put_metadata_cache(self, title_key: str, data, fetched_at: str) -> None: ...
